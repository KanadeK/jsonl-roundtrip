"""Regenerate real-tool synthetic NDJSON fixtures and verify bundle-only recovery.

Install scripts/export-requirements.txt and this project in a disposable venv.
Default mode compares regenerated bytes with committed fixtures; --write-fixtures
explicitly refreshes only the two tool-generated fixture files. Source-derived
Elasticsearch/MongoDB fixtures are not presented as outputs of live services.
"""

import argparse
import hashlib
import importlib.metadata
import json
import tempfile
from pathlib import Path

VERSIONS = {"duckdb": "2.0.0", "pandas": "3.1.0"}
SENTINEL = "SYNTHETIC_PRIVATE_EXPORT_SENTINEL_94c2"
HUGE_POSITIVE = "170141183460469231731687303715884105727"
HUGE_NEGATIVE = "-170141183460469231731687303715884105728"


def require_versions():
    for package, expected in VERSIONS.items():
        try:
            installed = importlib.metadata.version(package)
        except importlib.metadata.PackageNotFoundError:
            raise SystemExit("Install the pinned development-only export requirements") from None
        if installed != expected:
            raise SystemExit("Pinned exporter version mismatch")


def records():
    """Original project-owned synthetic rows; no external or private dataset."""
    return [
        {
            "id": 1,
            "message": "first line\nsecond line " + SENTINEL,
            "label": "雪🙂",
            "optional": None,
            "nested": {"values": [1, None, True]},
            "large_number": 9007199254740993,
        },
        {
            "id": 2,
            "message": 'quote " and slash \\',
            "label": "café",
            "optional": "present",
            "nested": {"values": [], "note": None},
            "large_number": 9223372036854775807,
        },
        {
            "id": 3,
            "message": "CR\rLF\nend",
            "label": "LS\u2028PS\u2029",
            "optional": None,
            "nested": {"event": {"synthetic": True}},
            "large_number": -9223372036854775808,
        },
    ]


def duckdb_export(directory):
    import duckdb

    path = directory / "duckdb-copy.ndjson"
    connection = duckdb.connect(":memory:")
    try:
        # No extension download is permitted during fixture generation.
        connection.execute("SET autoinstall_known_extensions=false")
        connection.execute(
            "CREATE TABLE synthetic_exports (id BIGINT, message VARCHAR, label VARCHAR, "
            "optional VARCHAR, nested JSON, large_number HUGEINT)"
        )
        values = records()
        values[0]["large_number"] = HUGE_POSITIVE
        values[1]["large_number"] = HUGE_NEGATIVE
        connection.executemany(
            "INSERT INTO synthetic_exports VALUES "
            "(?, ?, ?, ?, CAST(? AS JSON), CAST(? AS HUGEINT))",
            [
                (
                    row["id"],
                    row["message"],
                    row["label"],
                    row["optional"],
                    json.dumps(row["nested"], ensure_ascii=False),
                    str(row["large_number"]),
                )
                for row in values
            ],
        )
        quoted_path = "'" + path.as_posix().replace("'", "''") + "'"
        connection.execute(
            "COPY (SELECT * FROM synthetic_exports ORDER BY id) TO "
            + quoted_path
            + " (FORMAT JSON, ARRAY false)"
        )
    finally:
        connection.close()
    raw = path.read_bytes()
    decoded = decode_rows(raw, 3)
    if decoded[0]["large_number"] != int(HUGE_POSITIVE) or decoded[1]["large_number"] != int(
        HUGE_NEGATIVE
    ):
        raise RuntimeError("DuckDB fixture did not preserve the expected synthetic HUGEINT values")
    common_semantics(decoded)
    return path.name, raw


def pandas_export(directory):
    import pandas as pd

    path = directory / "pandas-records.ndjson"
    # Object dtype avoids accidental nullable integer-to-float conversion before
    # export. This verifies actual pandas output, not a stdlib JSON surrogate.
    frame = pd.DataFrame(records(), dtype=object)
    frame.to_json(path, orient="records", lines=True, force_ascii=False, compression=None)
    raw = path.read_bytes()
    decoded = decode_rows(raw, 3)
    common_semantics(decoded)
    if [row["large_number"] for row in decoded] != [
        9007199254740993,
        9223372036854775807,
        -9223372036854775808,
    ]:
        raise RuntimeError("pandas fixture did not preserve the specified synthetic integers")
    return path.name, raw


def decode_rows(raw, count):
    if not raw.endswith(b"\n") or raw.count(b"\n") != count:
        raise RuntimeError("Exporter did not produce the expected physical record count")
    return [json.loads(line) for line in raw.split(b"\n")[:-1]]


def common_semantics(decoded):
    if (
        decoded[0]["message"] != "first line\nsecond line " + SENTINEL
        or decoded[0]["label"] != "雪🙂"
        or decoded[0]["optional"] is not None
        or decoded[0]["nested"] != {"values": [1, None, True]}
        or decoded[1]["message"] != 'quote " and slash \\'
        or decoded[2]["label"] != "LS\u2028PS\u2029"
    ):
        raise RuntimeError("Exporter semantics differ from original synthetic source rows")


def prove_bundle_only(directory, name, raw):
    from jsonl_roundtrip.core import inspect, partition, restore

    source = directory / name
    source.write_bytes(raw)
    before = hashlib.sha256(raw).hexdigest()
    checked = inspect(source, objects_only=True)
    bundle = directory / (name + ".bundle")
    summary = partition(source, bundle, objects_only=True)
    if summary != checked or summary["accepted_lines"] != 3 or summary["rejected_lines"]:
        raise RuntimeError("Tool-generated NDJSON was unexpectedly quarantined")
    if SENTINEL in json.dumps(summary):
        raise RuntimeError("Diagnostics disclosed synthetic private content")
    if source.read_bytes() != raw:
        raise RuntimeError("Source changed during partition")
    source.unlink()
    restored = directory / (name + ".restored")
    recovered = restore(bundle, restored)
    if source.exists() or restored.read_bytes() != raw or recovered["sha256"] != before:
        raise RuntimeError("Bundle-only byte restoration failed")
    # A deliberately damaged variant comes from actual exported bytes, not a
    # fabricated claim about a production user's damaged export.
    lines = raw.split(b"\n")[:-1]
    damaged = b"\r\n".join((lines[0], b'{"truncated":', b"\xff", lines[1], lines[2]))
    damaged_source = directory / (name + ".damaged")
    damaged_source.write_bytes(damaged)
    damaged_bundle = directory / (name + ".damaged.bundle")
    rejected = partition(damaged_source, damaged_bundle)
    if (rejected["total_lines"], rejected["accepted_lines"], rejected["rejected_lines"]) != (
        5,
        3,
        2,
    ):
        raise RuntimeError("Damaged exported-record classifications disagree")
    damaged_source.unlink()
    damaged_output = directory / (name + ".damaged.restored")
    restore(damaged_bundle, damaged_output)
    if damaged_output.read_bytes() != damaged:
        raise RuntimeError("Damaged export was not reconstructed byte-for-byte")
    return {
        "fixture": name,
        "producer_records": 3,
        "damaged_accepted": 3,
        "damaged_rejected": 2,
        "bytes": len(raw),
        "sha256": before,
        "bundle_only_roundtrip": True,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--write-fixtures", action="store_true", help="refresh two tool-generated fixtures"
    )
    args = parser.parse_args()
    require_versions()
    fixture_dir = Path(__file__).resolve().parents[1] / "tests" / "fixtures" / "exports"
    fixture_dir.mkdir(parents=True, exist_ok=True)
    results = []
    with tempfile.TemporaryDirectory(prefix="jsonl-export-producers-") as temporary:
        directory = Path(temporary)
        for producer in (duckdb_export, pandas_export):
            name, raw = producer(directory)
            fixture = fixture_dir / name
            if args.write_fixtures:
                if fixture.is_symlink() or (fixture.exists() and not fixture.is_file()):
                    raise RuntimeError("Refusing to replace a linked or nonregular fixture")
                fixture.write_bytes(raw)
            elif not fixture.is_file() or fixture.read_bytes() != raw:
                raise RuntimeError("Generated bytes differ from the committed synthetic fixture")
            results.append(prove_bundle_only(directory, name, raw))
    print(json.dumps({"producer_versions": VERSIONS, "exports": results}, sort_keys=True))


if __name__ == "__main__":
    main()
